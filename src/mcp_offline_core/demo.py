"""Демонстрационный инструмент для офлайн-приёмки."""


def echo(arguments, _context):
    """Вернуть проверенное поле `text` в объекте с ключом `echo`.

    Схема манифеста задаёт тип и длину строки до вызова функции.
    Операция работает только с переданным текстом, поэтому контекст не используется.
    """
    return {"echo": arguments["text"]}
